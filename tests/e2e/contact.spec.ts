import { expect, test } from '@playwright/test'
test.use({ reducedMotion: 'reduce' })
test('Contact opens a usable panel and copies the email without an email app', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/?fallback')
  const contact = page.getByRole('navigation', { name: 'Navigation principale' }).getByRole('button', { name: 'Contact', exact: true })
  await contact.click()
  const panel = page.getByRole('dialog', { name: 'Et si on créait quelque chose ?' })
  await expect(panel).toBeVisible()
  await expect(panel.getByLabel('Mon adresse email')).toHaveValue('Linelodie2004@gmail.com')
  await panel.getByRole('button', { name: 'Copier l’adresse' }).click()
  await expect(panel.getByRole('status')).toHaveText('Adresse copiée !')
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('Linelodie2004@gmail.com')
  await page.keyboard.press('Escape')
  await expect(panel).toHaveCount(0)
  await expect(contact).toBeFocused()
})
