import { expect, test } from '@playwright/test'
test.use({ reducedMotion: 'reduce' })
test('all six experiments respond to keyboard input and release their canvas on close', async ({ page }) => {
  test.setTimeout(90000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/playground?fallback')
  const cards = page.locator('.experiment-card')
  await expect(cards).toHaveCount(6)
  for (let index = 0; index < 6; index++) {
    await cards.nth(index).click()
    const dialog = page.getByRole('dialog'), canvas = dialog.locator('canvas')
    await expect(dialog).toBeVisible()
    await canvas.focus()
    const before = await canvas.evaluate(node => (node as HTMLCanvasElement).toDataURL())
    await page.keyboard.press('ArrowRight')
    await page.keyboard.press('Enter')
    await expect.poll(() => canvas.evaluate(node => (node as HTMLCanvasElement).toDataURL())).not.toBe(before)
    await dialog.getByRole('button', { name: 'Pause', exact: true }).click()
    await expect(dialog.getByRole('button', { name: 'Reprendre', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await dialog.getByRole('button', { name: /Recommencer/ }).click()
    await expect(dialog.getByRole('button', { name: 'Pause', exact: true })).toHaveAttribute('aria-pressed', 'false')
    await page.keyboard.press('Escape')
    await expect(dialog).not.toBeVisible()
    await expect(dialog.locator('canvas')).toHaveCount(0)
    await expect(cards.nth(index)).toBeFocused()
  }
  expect(errors).toEqual([])
})
