import { expect, test } from '@playwright/test'
test.use({ reducedMotion: 'reduce' })
test('project navigation, language, history and Escape', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('link', { name: 'StreamFlix', exact: true })).toHaveAttribute('href', '/projets/streamflix')
  await expect(page.getByRole('link', { name: 'YORU', exact: true })).toHaveAttribute('href', '/projets/yoru')
  await page.getByRole('navigation', { name: 'Navigation principale' }).getByRole('link', { name: 'Projets', exact: true }).click()
  await expect(page).toHaveURL(/\/projets$/)
  await expect(page.locator('.project-row')).toHaveCount(4)
  await page.getByRole('link', { name: 'EN', exact: true }).click()
  await expect(page).toHaveURL(/\/en\/projects$/)
  await page.goBack()
  await expect(page).toHaveURL(/\/projets$/)
  await page.keyboard.press('Escape')
  await expect(page).toHaveURL(/\/$/)
  expect(errors).toEqual([])
})
test('direct mobile about route and local guestbook', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/en/about')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Elodie')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.goto('/')
  await page.getByRole('button', { name: 'Coucou', exact: true }).click()
  await page.locator('#guest-message').fill('Bonjour Elodie !')
  await page.getByRole('button', { name: 'Envoyer', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('flotte')
  await page.locator('#guest-message').fill('Encore un petit mot !')
  await page.getByRole('button', { name: 'Envoyer', exact: true }).click()
  await expect(page.locator('#guest-message')).toHaveValue('')
  await expect(page.getByRole('status')).toContainText('flotte')
  await page.keyboard.press('Escape')
  await expect(page.locator('#guest-message')).toHaveCount(0)
})
test('playground dialog restores keyboard focus', async ({ page }) => {
  await page.goto('/playground')
  const first = page.locator('.experiment-card').first()
  await first.click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(first).toBeFocused()
})
test('content exists without JavaScript', async ({ browser }) => {
  const context = await browser.newContext({ javaScriptEnabled: false, baseURL: test.info().project.use.baseURL })
  const page = await context.newPage()
  await page.goto('/projets/yoru')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('YORU')
  await expect(page.getByText('Le défi', { exact: true })).toBeVisible()
  await context.close()
})
